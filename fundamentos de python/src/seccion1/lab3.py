# Se imprime una flecha utilizando una sola función print().
# \n sirve para hacer un salto de línea.
# Cada línea se multiplica por 2 para mostrar dos flechas lado a lado.

print(
"    *        "  + "\n"
"   * *       "  + "\n"
"  *   *      "  + "\n"
" *     *     "  + "\n"
"***   ***    "  + "\n"
"  *   *      "  + "\n"
"  *   *      "  + "\n"
"  *****      " 
)

print(
("    *      " * 2) + "\n" +
("   * *     " * 2) + "\n" +
("  *   *    " * 2) + "\n" +
(" *     *   " * 2) + "\n" +
("***   ***  " * 2) + "\n" +
("  *   *    " * 2) + "\n" +
("  *   *    " * 2) + "\n" +
("  *****    " * 2)
)